import http from "node:http";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const packageRoot = path.resolve(__dirname, "../..");
const publicDir = path.join(__dirname, "public");

// In-memory state for the active replica mock session
let activeHarRecords = [];
let activeEndpoints = [];

/** Match incoming URL to HAR template */
function matchHarRecord(method, pathname, records) {
  const normMethod = method.toUpperCase();
  // Try exact match first
  let match = records.find(r => r.method === normMethod && r.path === pathname);
  if (match) return match;

  // Try path pattern match (replacing dynamic segments like numbers, uids)
  const segments = pathname.split("/").filter(Boolean);
  match = records.find(r => {
    if (r.method !== normMethod) return false;
    const rSegments = r.path.split("/").filter(Boolean);
    if (rSegments.length !== segments.length) return false;
    return rSegments.every((seg, idx) => {
      const incoming = segments[idx];
      if (seg === incoming) return true;
      // Numeric ID or alphanumeric UID match
      if (/^\d+$/.test(seg) || /^[a-zA-Z0-9_-]{6,}$/.test(seg)) return true;
      return false;
    });
  });
  return match || records.find(r => r.method === normMethod);
}

/** Parse HAR content into structured endpoints */
function parseHarToEndpoints(har) {
  const entries = har.log?.entries || [];
  const endpointsMap = new Map();
  const records = [];

  entries.forEach((entry, idx) => {
    const req = entry.request;
    const res = entry.response;
    let urlObj;
    try {
      urlObj = new URL(req.url);
    } catch {
      urlObj = { pathname: req.url, searchParams: new URLSearchParams() };
    }

    const pathname = urlObj.pathname;
    const method = req.method.toUpperCase();
    const status = res.status || 200;
    const mimeType = res.content?.mimeType || "application/json";
    const bodyText = res.content?.text || "{}";

    records.push({
      id: idx + 1,
      method,
      path: pathname,
      fullUrl: req.url,
      status,
      mimeType,
      bodyText,
      reqBody: req.postData?.text || null
    });

    // Simplify path into template
    const templateSegments = pathname.split("/").map(seg => {
      if (/^\d+$/.test(seg)) return "{id}";
      if (/^[a-zA-Z0-9_-]{10,}$/.test(seg)) return "{uid}";
      return seg;
    });
    const templatePath = templateSegments.join("/");
    const key = `${method} ${templatePath}`;

    if (!endpointsMap.has(key)) {
      endpointsMap.set(key, {
        method,
        pathTemplate: templatePath,
        examplePath: pathname,
        statuses: [status],
        queryParameters: [...(urlObj.searchParams?.keys() || [])],
        bodySample: req.postData?.text ? tryParseJson(req.postData.text) : null,
        responseSample: tryParseJson(bodyText),
        occurrences: 1
      });
    } else {
      const existing = endpointsMap.get(key);
      existing.occurrences++;
      if (!existing.statuses.includes(status)) existing.statuses.push(status);
    }
  });

  return { records, endpoints: Array.from(endpointsMap.values()) };
}

function tryParseJson(text) {
  try {
    return JSON.parse(text);
  } catch {
    return text;
  }
}

/** Generate a standalone Zero-Docker mock server */
function generateStandaloneServerCode(records, endpoints) {
  return `// REA Standalone Zero-Docker Application Replica Server
// Generated by REA Studio
import http from "node:http";

const PORT = process.env.PORT || 4000;
const RECORDS = ${JSON.stringify(records, null, 2)};
const ENDPOINTS = ${JSON.stringify(endpoints, null, 2)};

// In-memory mock database state
const state = new Map();

function matchRecord(method, pathname) {
  const normMethod = method.toUpperCase();
  let match = RECORDS.find(r => r.method === normMethod && r.path === pathname);
  if (match) return match;

  const segments = pathname.split("/").filter(Boolean);
  match = RECORDS.find(r => {
    if (r.method !== normMethod) return false;
    const rSegs = r.path.split("/").filter(Boolean);
    if (rSegs.length !== segments.length) return false;
    return rSegs.every((seg, i) => seg === segments[i] || /^\\d+$/.test(seg) || /^[a-zA-Z0-9_-]{6,}$/.test(seg));
  });
  return match || RECORDS.find(r => r.method === normMethod);
}

const server = http.createServer((req, res) => {
  // CORS
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Access-Control-Allow-Methods", "GET, POST, PUT, DELETE, PATCH, OPTIONS");
  res.setHeader("Access-Control-Allow-Headers", "Content-Type, Authorization");

  if (req.method === "OPTIONS") {
    res.writeHead(204);
    res.end();
    return;
  }

  const url = new URL(req.url, \`http://\${req.headers.host}\`);
  const pathname = url.pathname;

  if (pathname === "/" || pathname === "/_info") {
    res.writeHead(200, { "Content-Type": "application/json" });
    res.end(JSON.stringify({
      name: "REA Standalone Application Replica",
      endpoints: ENDPOINTS.map(e => \`\${e.method} \${e.pathTemplate}\`),
      totalRecords: RECORDS.length
    }, null, 2));
    return;
  }

  const record = matchRecord(req.method, pathname);
  if (record) {
    res.writeHead(record.status, { "Content-Type": record.mimeType });
    res.end(record.bodyText);
  } else {
    res.writeHead(404, { "Content-Type": "application/json" });
    res.end(JSON.stringify({ error: "Endpoint not found in replica capture", pathname, method: req.method }));
  }
});

server.listen(PORT, () => {
  console.log(\`[REA Replica] Server listening at http://localhost:\${PORT}\`);
  console.log(\`[REA Replica] Serving \${ENDPOINTS.length} replicated endpoints without Docker.\`);
});
`;
}

/** Create and start the REA Studio server */
export function startStudio(port = 3000) {
  // Pre-load default HAR if available
  const defaultHarPath = path.join(packageRoot, "test-app.har");
  if (fs.existsSync(defaultHarPath)) {
    try {
      const parsed = parseHarToEndpoints(JSON.parse(fs.readFileSync(defaultHarPath, "utf8")));
      activeHarRecords = parsed.records;
      activeEndpoints = parsed.endpoints;
    } catch (e) {
      console.warn("Could not load default HAR:", e.message);
    }
  }

  const server = http.createServer(async (req, res) => {
    // Enable CORS
    res.setHeader("Access-Control-Allow-Origin", "*");
    res.setHeader("Access-Control-Allow-Methods", "GET, POST, OPTIONS");
    res.setHeader("Access-Control-Allow-Headers", "Content-Type");

    if (req.method === "OPTIONS") {
      res.writeHead(204);
      res.end();
      return;
    }

    const parsedUrl = new URL(req.url, `http://${req.headers.host}`);
    const pathname = parsedUrl.pathname;

    // Handle Mock Routes (/mock/...)
    if (pathname.startsWith("/mock/")) {
      const mockPath = pathname.slice("/mock".length);
      const record = matchHarRecord(req.method, mockPath, activeHarRecords);
      if (record) {
        res.writeHead(record.status, {
          "Content-Type": record.mimeType,
          "X-REA-Replica": "true",
          "X-REA-Matched-Record": String(record.id)
        });
        res.end(record.bodyText);
      } else {
        res.writeHead(404, { "Content-Type": "application/json" });
        res.end(JSON.stringify({
          error: "Endpoint not found in active replica session",
          path: mockPath,
          method: req.method
        }));
      }
      return;
    }

    // Handle API endpoints
    if (pathname === "/api/status") {
      let winNativeStatus = false;
      const nativePath = path.join(packageRoot, "native/windows/build/rea-windows-x64.node");
      if (fs.existsSync(nativePath)) winNativeStatus = true;

      res.writeHead(200, { "Content-Type": "application/json" });
      res.end(JSON.stringify({
        ok: true,
        name: "REA Studio",
        version: "6.8.0-pro",
        platform: process.platform,
        arch: process.arch,
        nodeVersion: process.version,
        nativeWindowsEngine: winNativeStatus,
        activeEndpointsCount: activeEndpoints.length,
        activeRecordsCount: activeHarRecords.length,
        toolsCount: 229,
        commandsCount: 175
      }));
      return;
    }

    if (pathname === "/api/har/endpoints") {
      res.writeHead(200, { "Content-Type": "application/json" });
      res.end(JSON.stringify({
        ok: true,
        endpoints: activeEndpoints,
        totalRecords: activeHarRecords.length
      }));
      return;
    }

    if (pathname === "/api/har/upload" && req.method === "POST") {
      let body = "";
      req.on("data", chunk => (body += chunk));
      req.on("end", () => {
        try {
          const payload = JSON.parse(body);
          const harData = payload.har || payload;
          const { records, endpoints } = parseHarToEndpoints(harData);
          activeHarRecords = records;
          activeEndpoints = endpoints;
          res.writeHead(200, { "Content-Type": "application/json" });
          res.end(JSON.stringify({
            ok: true,
            recordsCount: records.length,
            endpointsCount: endpoints.length,
            endpoints
          }));
        } catch (err) {
          res.writeHead(400, { "Content-Type": "application/json" });
          res.end(JSON.stringify({ ok: false, error: err.message }));
        }
      });
      return;
    }

    if (pathname === "/api/mock/send" && req.method === "POST") {
      let body = "";
      req.on("data", chunk => (body += chunk));
      req.on("end", () => {
        try {
          const { method = "GET", path: targetPath = "/" } = JSON.parse(body);
          const record = matchHarRecord(method, targetPath, activeHarRecords);
          if (record) {
            res.writeHead(200, { "Content-Type": "application/json" });
            res.end(JSON.stringify({
              ok: true,
              matched: true,
              status: record.status,
              mimeType: record.mimeType,
              body: tryParseJson(record.bodyText),
              matchedRecordId: record.id,
              originalUrl: record.fullUrl
            }));
          } else {
            res.writeHead(200, { "Content-Type": "application/json" });
            res.end(JSON.stringify({
              ok: true,
              matched: false,
              status: 404,
              body: { error: "No matching captured endpoint in HAR evidence", method, path: targetPath }
            }));
          }
        } catch (err) {
          res.writeHead(400, { "Content-Type": "application/json" });
          res.end(JSON.stringify({ ok: false, error: err.message }));
        }
      });
      return;
    }

    if (pathname === "/api/export-replica" && req.method === "POST") {
      let body = "";
      req.on("data", chunk => (body += chunk));
      req.on("end", () => {
        try {
          const { targetDir = "standalone-replica" } = body ? JSON.parse(body) : {};
          const destDir = path.resolve(packageRoot, targetDir);
          fs.mkdirSync(destDir, { recursive: true });

          const serverCode = generateStandaloneServerCode(activeHarRecords, activeEndpoints);
          fs.writeFileSync(path.join(destDir, "server.mjs"), serverCode);

          const packageJson = {
            name: "rea-replicated-app",
            version: "1.0.0",
            type: "module",
            scripts: {
              start: "node server.mjs"
            }
          };
          fs.writeFileSync(path.join(destDir, "package.json"), JSON.stringify(packageJson, null, 2));

          const readme = `# REA Standalone Zero-Docker Replicated App
This mock server was generated by REA Studio from captured HAR evidence.
It runs completely standalone on Node.js without requiring Docker or external dependencies.

## Run It
\`\`\`bash
node server.mjs
\`\`\`
Server runs at http://localhost:4000
Total Replicated Endpoints: ${activeEndpoints.length}
`;
          fs.writeFileSync(path.join(destDir, "README.md"), readme);

          res.writeHead(200, { "Content-Type": "application/json" });
          res.end(JSON.stringify({
            ok: true,
            directory: destDir,
            endpointsCount: activeEndpoints.length,
            recordsCount: activeHarRecords.length
          }));
        } catch (err) {
          res.writeHead(500, { "Content-Type": "application/json" });
          res.end(JSON.stringify({ ok: false, error: err.message }));
        }
      });
      return;
    }

    if (pathname === "/api/electron/demo-graph") {
      // Returns high-level graph data from the analyzed Electron application
      res.writeHead(200, { "Content-Type": "application/json" });
      res.end(JSON.stringify({
        ok: true,
        app: "Notes Application",
        processes: [
          { id: "proc-main", name: "Main Process", type: "node", file: "main.js" },
          { id: "proc-preload", name: "Preload Bridge", type: "sandbox", file: "preload.js" },
          { id: "proc-renderer", name: "Renderer Window", type: "browser", file: "renderer.js" }
        ],
        contextBridges: [
          { name: "notesApi", exposedIn: "window.notesApi", methods: ["getAll()", "create(note)", "delete(id)"] }
        ],
        ipcChannels: [
          {
            name: "notes:get-all",
            direction: "bidirectional",
            mainMode: "handle (ipcMain.handle)",
            rendererMode: "invoke (ipcRenderer.invoke)",
            status: "secure"
          },
          {
            name: "notes:create",
            direction: "bidirectional",
            mainMode: "handle (ipcMain.handle)",
            rendererMode: "invoke (ipcRenderer.invoke)",
            status: "secure"
          },
          {
            name: "notes:delete",
            direction: "unidirectional",
            mainMode: "listen (ipcMain.on)",
            rendererMode: "send (ipcRenderer.send)",
            status: "secure"
          }
        ]
      }));
      return;
    }

    // Static file serving
    let filePath = path.join(publicDir, pathname === "/" ? "index.html" : pathname);
    if (!filePath.startsWith(publicDir)) {
      res.writeHead(403);
      res.end("Forbidden");
      return;
    }

    if (!fs.existsSync(filePath) || fs.statSync(filePath).isDirectory()) {
      filePath = path.join(publicDir, "index.html");
    }

    const ext = path.extname(filePath);
    const mimeTypes = {
      ".html": "text/html; charset=utf-8",
      ".js": "application/javascript; charset=utf-8",
      ".css": "text/css; charset=utf-8",
      ".json": "application/json",
      ".svg": "image/svg+xml",
      ".png": "image/png"
    };

    res.writeHead(200, { "Content-Type": mimeTypes[ext] || "text/plain" });
    fs.createReadStream(filePath).pipe(res);
  });

  server.listen(port, () => {
    console.log(`\n========================================================`);
    console.log(`  🚀 REA Studio UI is running at http://localhost:${port}`);
    console.log(`  ⚡ Reverse Engineering & Zero-Docker App Replicator`);
    console.log(`  Press Ctrl+C to stop.`);
    console.log(`========================================================\n`);
  });

  return server;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const port = process.env.PORT ? parseInt(process.env.PORT, 10) : 3000;
  startStudio(port);
}
